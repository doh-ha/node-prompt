"""
프롬프트 템플릿 관리 모듈
각 노드 타입별 추천 프롬프트를 중앙에서 관리
"""

def get_recommendation_prompt(current_prompt: str, node_type: str) -> str:
    """
    노드 타입에 맞는 추천 프롬프트를 반환합니다.
    
    Args:
        current_prompt: 현재 작업 프롬프트
        node_type: 노드 타입 ("role", "style", "audience", "length")
    
    Returns:
        OpenAI API에 전달할 추천 프롬프트
    """
    
    prompts = {
        "role": f"""
현재 작업: "{current_prompt}"

이 작업에 가장 적합한 AI 역할을 3-5개 추천해주세요. 각 역할은 구체적이고 전문적이어야 합니다.

응답 형식:
- 역할1: 설명
- 역할2: 설명
- 역할3: 설명

예시:
- 영어 교사: 영어 학습을 도와주는 전문가
- 일본어 전문가: 일본어 문법과 표현을 가르치는 전문가
""",
        "style": f"""
현재 작업: "{current_prompt}"

이 작업에 가장 적합한 작성 스타일을 3-5개 추천해주세요.

응답 형식:
- 스타일1: 설명
- 스타일2: 설명
- 스타일3: 설명

예시:
- 친근한 톤: 따뜻하고 친근한 말투
- 전문적인 톤: 정확하고 전문적인 표현
""",
        "audience": f"""
현재 작업: "{current_prompt}"

이 작업의 대상 독자를 3-5개 추천해주세요.

응답 형식:
- 대상1: 설명
- 대상2: 설명
- 대상3: 설명

예시:
- 초등학생: 6-12세 어린이 대상
- 중학생: 13-15세 청소년 대상
""",
        "length": f"""
현재 작업: "{current_prompt}"

이 작업에 적합한 길이를 3-5개 추천해주세요.

응답 형식:
- 길이1: 설명
- 길이2: 설명
- 길이3: 설명

예시:
- 짧게 (1-2문장): 간결하고 핵심적인 내용
- 보통 (3-5문장): 적당한 길이의 설명
""",
    }
    
    return prompts.get(
        node_type,
        f"'{current_prompt}' 작업에 적합한 {node_type}을 추천해주세요."
    )


def get_system_prompt() -> str:
    """추천 기능을 위한 시스템 프롬프트를 반환합니다."""
    return "당신은 프롬프트 엔지니어링 전문가입니다. 주어진 작업에 가장 적합한 요소들을 추천해주세요."

