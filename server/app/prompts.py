def get_system_prompt() -> str:
    """추천 기능을 위한 시스템 프롬프트를 반환합니다."""
    return """
당신은 '프롬프트 최적화 및 구조화'를 전문으로 하는 최고의 프롬프트 엔지니어링 전문가입니다.
당신의 목표는 사용자에게 가장 구체적이고 전문적인 요소들을 추천하여, 최종 출력물의 품질과 적합성을 극대화하는 것입니다.

[핵심 규칙]
1.  **현재 프롬프트(Current Prompt)를 면밀히 분석하고, 그 문맥에 완벽하게 일치하는 추천만을 제공해야 합니다.**
2.  **추천하는 각 항목은 구체적이고 전문적이며, 사용자 프롬프트에 즉시 추가될 수 있도록 명확해야 합니다.**
3.  **오직 요청된 JSON 형식으로만 응답해야 합니다. JSON 외의 어떠한 설명, 서론, 결론도 포함하지 마세요.**
"""

def get_recommendation_prompt(current_prompt: str, node_type: str) -> str:
    """
    노드 타입에 맞는 추천 프롬프트를 반환합니다.
    
    Args:
        current_prompt: 현재 작업 프롬프트
        node_type: 노드 타입 ("task", "role", "style", "audience", "length")
    
    Returns:
        OpenAI API에 전달할 추천 프롬프트 (JSON 형식 응답 요청)
    """
    
    # JSON 스키마를 미리 정의하여 응답 일관성을 확보
    json_schema = """
{
  "recommendations": [
    {
      "element": "추천 항목 (예: Task, Role, Style 등)",
      "description": "추천 항목에 대한 구체적인 설명"
    },
    // 최소 3개, 최대 5개의 추천 항목을 포함해야 함
  ]
}
"""

    prompts = {
        "task": f"""
[현재 프롬프트 분석]
현재 작업의 핵심 주제, 의도, 그리고 현재 누락된 구체적인 정보를 파악하세요.

[요청]
현재 프롬프트: "{current_prompt}"
이 작업을 **더 구체적, 명확, 풍성하게** 만들 수 있는 **3~5가지의 구체적인 개선 방향**을 추천해주세요. 개선 방향은 결과물의 질을 높이는 데 초점을 맞춰야 합니다.

[출력 형식]
반드시 다음 JSON 스키마를 준수하여 응답하세요.
{json_schema}

예시 JSON 항목:
{{ "element": "창의적 제약 조건 추가", "description": "특정 키워드/문맥 포함, 제외와 같은 제약을 추가하여 창의성을 증폭시킬 수 있습니다." }}
{{ "element": "사용할 수 있는 데이터 형태 명시", "description": "텍스트 외에 이미지, 데이터 테이블 등의 추가 자료가 필요한지 명시합니다." }}
""",
        "role": f"""
[현재 프롬프트 분석]
현재 프롬프트의 요구사항(주제, 난이도, 형식)을 충족하기 위해 AI가 갖추어야 할 전문성을 파악하세요.

[요청]
현재 프롬프트: "{current_prompt}"
이 작업에 가장 적합한 **3~5가지의 구체적이고 전문적인 AI 역할(Persona)**을 추천해주세요. 추천 역할은 해당 분야의 전문가처럼 행동하도록 유도해야 합니다.

[출력 형식]
반드시 다음 JSON 스키마를 준수하여 응답하세요.
{json_schema}

예시 JSON 항목:
{{ "element": "경험 많은 초등 교육 전문가", "description": "6-12세 아동의 인지 수준과 흥미를 고려하여 쉽고 재미있는 언어를 사용합니다." }}
{{ "element": "ISO 표준 문서 작성자", "description": "국제 표준화 기구(ISO)의 형식과 전문 용어를 엄격하게 준수하여 문서를 작성합니다." }}
""",
        "style": f"""
[현재 프롬프트 분석]
현재 프롬프트의 내용과 역할(Role)에 가장 잘 어울리는 어조, 형식, 분위기 등의 시각적/감성적 스타일을 파악하세요.

[요청]
현재 프롬프트: "{current_prompt}"
이 작업에 가장 적합한 **3~5가지의 구체적인 작성 스타일**을 추천해주세요. 스타일은 결과물의 최종적인 느낌을 결정하는 요소여야 합니다.

[출력 형식]
반드시 다음 JSON 스키마를 준수하여 응답하세요.
{json_schema}

예시 JSON 항목:
{{ "element": "설득력 있는 학술적 논조", "description": "객관적인 데이터와 논리를 바탕으로 신뢰감을 주는 학술적인 어조를 사용합니다." }}
{{ "element": "미니멀리즘 시적 표현", "description": "간결하고 함축적인 언어로 여백의 미를 살리며 핵심 감정을 전달합니다." }}
""",
        "audience": f"""
[현재 프롬프트 분석]
현재 프롬프트의 내용이 누구를 대상으로 할 때 가장 큰 효과를 낼 수 있을지 혹은 필수 대상이 누구인지 파악하세요.

[요청]
현재 프롬프트: "{current_prompt}"
이 작업의 잠재적인 **3~5가지 대상 독자**를 구체적인 특징과 함께 추천해주세요. 대상은 연령대, 전문성 수준, 문화적 배경 등을 포괄해야 합니다.

[출력 형식]
반드시 다음 JSON 스키마를 준수하여 응답하세요.
{json_schema}

예시 JSON 항목:
{{ "element": "IT 분야 비전공자 신입사원", "description": "전문 용어 사용을 최소화하고 비유와 예시를 통해 핵심 개념을 쉽게 이해하도록 돕습니다." }}
{{ "element": "데이터 분석 석사 과정 학생", "description": "최신 연구 동향과 고급 통계 개념을 포함하여 심도 있는 내용을 제공합니다." }}
""",
        "length": f"""
[현재 프롬프트 분석]
현재 프롬프트의 복잡성, 목표(정보 제공 vs. 요약), 그리고 대상(Audience)을 고려하여 적절한 길이를 파악하세요.

[요청]
현재 프롬프트: "{current_prompt}"
이 작업에 적합한 **3~5가지의 길이(분량) 옵션**을 구체적인 단위(문장 수, 단어 수, 문단 수, 시간 등)와 함께 추천해주세요.

[출력 형식]
반드시 다음 JSON 스키마를 준수하여 응답하세요.
{json_schema}

예시 JSON 항목:
{{ "element": "트위터 카드형 분량 (약 200자)", "description": "핵심 메시지만 전달하는 간결한 카드 뉴스 형식의 길이입니다." }}
{{ "element": "블로그 포스팅 분량 (약 1,500 단어)", "description": "하나의 주제에 대해 충분한 정보를 제공하고 독자의 흥미를 유발할 수 있는 길이입니다." }}
""",
    }
    
    return prompts.get(
        node_type,
        f"[오류] 정의되지 않은 노드 타입 '{node_type}'입니다. '{current_prompt}' 작업에 적합한 요소를 3개 추천해주세요."
    )